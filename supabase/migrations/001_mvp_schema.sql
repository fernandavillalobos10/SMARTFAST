        ALTER TABLE pedidos ADD CONSTRAINT pedidos_tipo_entrega_valido
            CHECK (tipo_entrega IN ('DOMICILIO', 'RECOGER')) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pedidos_direccion_segun_tipo') THEN
        ALTER TABLE pedidos ADD CONSTRAINT pedidos_direccion_segun_tipo
            CHECK (
                tipo_entrega IS NULL
                OR (tipo_entrega = 'DOMICILIO' AND direccion_entrega IS NOT NULL)
                OR (tipo_entrega = 'RECOGER' AND direccion_entrega IS NULL)
            ) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'entregas_estado_valido') THEN
        ALTER TABLE entregas ADD CONSTRAINT entregas_estado_valido
            CHECK (estado_entrega IN ('PENDIENTE', 'EN_PREPARACION', 'EN_CAMINO', 'ENTREGADO', 'CANCELADO')) NOT VALID;
    END IF;
END $$;

