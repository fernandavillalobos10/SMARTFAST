-- ============================================================
-- 6. ALTA AUTOMÁTICA DE PERFIL AL REGISTRARSE
-- Crea usuarios (rol CLIENTE) + clientes cuando se inserta en auth.users.
-- El rol nunca se toma de los metadatos enviados por el navegador.
-- ============================================================

CREATE OR REPLACE FUNCTION public.fn_crear_usuario_desde_auth()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_nombre VARCHAR(100);
    v_telefono VARCHAR(20);
    v_id_cliente BIGINT;
BEGIN
    v_nombre := COALESCE(NULLIF(trim(NEW.raw_user_meta_data->>'nombre'), ''), split_part(NEW.email, '@', 1));
    v_telefono := NULLIF(trim(NEW.raw_user_meta_data->>'telefono'), '');

    IF EXISTS (SELECT 1 FROM usuarios WHERE auth_id = NEW.id) THEN
        RETURN NEW;
    END IF;

    INSERT INTO clientes (nombre, telefono, correo)
    VALUES (v_nombre, v_telefono, NEW.email)
    RETURNING id_cliente INTO v_id_cliente;

    INSERT INTO usuarios (auth_id, nombre, correo, telefono, rol, id_cliente)
    VALUES (NEW.id, v_nombre, NEW.email, v_telefono, 'CLIENTE', v_id_cliente);

    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_auth_crear_usuario ON auth.users;
CREATE TRIGGER trg_auth_crear_usuario
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.fn_crear_usuario_desde_auth();

-- ============================================================
-- 7. CREAR PEDIDO (atómico)
-- p_items: [{"id_producto": 1, "cantidad": 2}, ...]
-- Reglas: un solo restaurante, precio histórico, dirección según tipo,
-- crea entregas (solo DOMICILIO) e historial. NO descuenta stock.
-- ============================================================

CREATE OR REPLACE FUNCTION public.crear_pedido(
    p_id_restaurante BIGINT,
    p_tipo_entrega VARCHAR,
    p_nombre_contacto VARCHAR,
    p_telefono_contacto VARCHAR,
    p_direccion_entrega VARCHAR,
    p_notas TEXT,
    p_items JSONB
)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_usuario usuarios%ROWTYPE;
    v_restaurante restaurantes%ROWTYPE;
    v_producto productos%ROWTYPE;
    v_item JSONB;
    v_cantidad INTEGER;
    v_direccion VARCHAR(200);
    v_id_cliente BIGINT;
    v_id_pedido BIGINT;
    v_subtotal DECIMAL(10,2) := 0;
    v_costo_envio DECIMAL(10,2);
BEGIN
    IF p_tipo_entrega IS NULL OR p_tipo_entrega NOT IN ('DOMICILIO', 'RECOGER') THEN
        RAISE EXCEPTION 'Tipo de entrega inválido';
    END IF;
    IF COALESCE(trim(p_nombre_contacto), '') = '' OR COALESCE(trim(p_telefono_contacto), '') = '' THEN
        RAISE EXCEPTION 'El nombre y el teléfono de contacto son obligatorios';
    END IF;

    IF p_tipo_entrega = 'DOMICILIO' THEN
        v_direccion := NULLIF(trim(p_direccion_entrega), '');
        IF v_direccion IS NULL THEN
            RAISE EXCEPTION 'La dirección de entrega es obligatoria para pedidos a domicilio';
        END IF;
    END IF;

    IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'El pedido no tiene productos';
    END IF;

    SELECT * INTO v_restaurante FROM restaurantes WHERE id_restaurante = p_id_restaurante AND activo;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El restaurante no está disponible';
    END IF;

    SELECT * INTO v_usuario FROM usuarios WHERE auth_id = auth.uid();

    IF v_usuario.id_cliente IS NOT NULL THEN
        v_id_cliente := v_usuario.id_cliente;
    ELSE
        INSERT INTO clientes (nombre, telefono, direccion, correo)
        VALUES (trim(p_nombre_contacto), trim(p_telefono_contacto), v_direccion, v_usuario.correo)
        RETURNING id_cliente INTO v_id_cliente;

        IF v_usuario.id_usuario IS NOT NULL THEN
            UPDATE usuarios SET id_cliente = v_id_cliente WHERE id_usuario = v_usuario.id_usuario;
        END IF;
    END IF;

    v_costo_envio := CASE WHEN p_tipo_entrega = 'DOMICILIO' THEN v_restaurante.costo_envio_base ELSE 0 END;

    INSERT INTO pedidos (
        id_cliente, id_usuario, id_restaurante, estado, tipo_entrega,
        nombre_contacto, telefono_contacto, direccion_entrega, notas, costo_envio
    )
    VALUES (
        v_id_cliente, v_usuario.id_usuario, p_id_restaurante, 'CREADO', p_tipo_entrega,
        trim(p_nombre_contacto), trim(p_telefono_contacto), v_direccion, NULLIF(trim(p_notas), ''), v_costo_envio
    )
    RETURNING id_pedido INTO v_id_pedido;

    FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
        v_cantidad := (v_item->>'cantidad')::INTEGER;
        IF v_cantidad IS NULL OR v_cantidad <= 0 THEN
            RAISE EXCEPTION 'Cantidad inválida';
        END IF;

        SELECT * INTO v_producto FROM productos WHERE id_producto = (v_item->>'id_producto')::BIGINT;
        IF NOT FOUND OR NOT v_producto.disponible OR NOT v_producto.activo THEN
            RAISE EXCEPTION 'Un producto del carrito ya no está disponible';
        END IF;
        IF v_producto.id_restaurante IS DISTINCT FROM p_id_restaurante THEN
            RAISE EXCEPTION 'Todos los productos deben ser del mismo restaurante';
        END IF;
        IF v_producto.stock < v_cantidad THEN
            RAISE EXCEPTION 'Stock insuficiente para "%"', v_producto.nombre;
        END IF;

        INSERT INTO detalle_pedido (id_pedido, id_producto, cantidad, precio_unitario)
        VALUES (v_id_pedido, v_producto.id_producto, v_cantidad, v_producto.precio);

        v_subtotal := v_subtotal + v_producto.precio * v_cantidad;
    END LOOP;

    UPDATE pedidos
    SET subtotal = v_subtotal, total = v_subtotal + v_costo_envio
    WHERE id_pedido = v_id_pedido;

    IF p_tipo_entrega = 'DOMICILIO' THEN
        INSERT INTO entregas (id_pedido, direccion_entrega, estado_entrega)
        VALUES (v_id_pedido, v_direccion, 'PENDIENTE');
    END IF;

    INSERT INTO historial_estado_pedido (id_pedido, estado_anterior, estado_nuevo, id_usuario)
    VALUES (v_id_pedido, NULL, 'CREADO', v_usuario.id_usuario);

    RETURN v_id_pedido;
END $$;

-- ============================================================
-- 8. CAMBIAR ESTADO DE PEDIDO (atómico)
-- Flujo: CREADO -> ACEPTADO -> EN_PREPARACION -> EN_CAMINO -> ENTREGADO
--        RECOGER salta EN_CAMINO (EN_PREPARACION -> ENTREGADO).
--        CANCELADO desde CREADO, ACEPTADO o EN_PREPARACION.
-- Stock: se descuenta al ACEPTAR y se devuelve al CANCELAR si ya se descontó.
-- Permisos: el PROPIETARIO del restaurante; el cliente solo puede cancelar
-- su propio pedido mientras está CREADO.
-- ============================================================

CREATE OR REPLACE FUNCTION public.cambiar_estado_pedido(
    p_id_pedido BIGINT,
    p_estado_nuevo VARCHAR,
    p_comentario TEXT DEFAULT NULL
)
RETURNS VARCHAR LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_pedido pedidos%ROWTYPE;
    v_usuario usuarios%ROWTYPE;
    v_linea RECORD;
    v_es_propietario BOOLEAN;
    v_es_cliente BOOLEAN;
    v_permitido BOOLEAN;
BEGIN
    SELECT * INTO v_pedido FROM pedidos WHERE id_pedido = p_id_pedido FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Pedido no encontrado';
    END IF;

    SELECT * INTO v_usuario FROM usuarios WHERE auth_id = auth.uid();
    IF v_usuario.id_usuario IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión';
    END IF;

    v_es_propietario := COALESCE(v_usuario.rol = 'PROPIETARIO' AND v_usuario.id_restaurante = v_pedido.id_restaurante, FALSE);
    v_es_cliente := COALESCE(v_pedido.id_usuario = v_usuario.id_usuario, FALSE);

    IF NOT v_es_propietario
       AND NOT (v_es_cliente AND p_estado_nuevo = 'CANCELADO' AND v_pedido.estado = 'CREADO') THEN
        RAISE EXCEPTION 'No tienes permiso para cambiar este pedido';
    END IF;

    v_permitido := CASE v_pedido.estado
        WHEN 'CREADO' THEN p_estado_nuevo IN ('ACEPTADO', 'CANCELADO')
        WHEN 'ACEPTADO' THEN p_estado_nuevo IN ('EN_PREPARACION', 'CANCELADO')
        WHEN 'EN_PREPARACION' THEN
            p_estado_nuevo = 'CANCELADO'
            OR (p_estado_nuevo = 'EN_CAMINO' AND v_pedido.tipo_entrega = 'DOMICILIO')
            OR (p_estado_nuevo = 'ENTREGADO' AND v_pedido.tipo_entrega = 'RECOGER')
        WHEN 'EN_CAMINO' THEN p_estado_nuevo = 'ENTREGADO'
        ELSE FALSE
    END;
    IF NOT COALESCE(v_permitido, FALSE) THEN
        RAISE EXCEPTION 'Transición no permitida: % -> %', v_pedido.estado, p_estado_nuevo;
    END IF;

    IF p_estado_nuevo = 'ACEPTADO' THEN
        FOR v_linea IN
            SELECT d.id_producto, p.nombre, SUM(d.cantidad) AS cantidad
            FROM detalle_pedido d JOIN productos p ON p.id_producto = d.id_producto
            WHERE d.id_pedido = p_id_pedido
            GROUP BY d.id_producto, p.nombre
            ORDER BY d.id_producto
        LOOP
            UPDATE productos SET stock = stock - v_linea.cantidad
            WHERE id_producto = v_linea.id_producto AND stock >= v_linea.cantidad;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'Stock insuficiente para "%"', v_linea.nombre;
            END IF;
        END LOOP;
        UPDATE pedidos SET stock_descontado = TRUE WHERE id_pedido = p_id_pedido;

    ELSIF p_estado_nuevo = 'CANCELADO' AND v_pedido.stock_descontado THEN
        FOR v_linea IN
            SELECT d.id_producto, SUM(d.cantidad) AS cantidad
            FROM detalle_pedido d
            WHERE d.id_pedido = p_id_pedido
            GROUP BY d.id_producto
            ORDER BY d.id_producto
        LOOP
            UPDATE productos SET stock = stock + v_linea.cantidad WHERE id_producto = v_linea.id_producto;
        END LOOP;
        UPDATE pedidos SET stock_descontado = FALSE WHERE id_pedido = p_id_pedido;
    END IF;

    UPDATE pedidos SET estado = p_estado_nuevo WHERE id_pedido = p_id_pedido;

    UPDATE entregas
    SET estado_entrega = CASE WHEN p_estado_nuevo = 'ACEPTADO' THEN estado_entrega ELSE p_estado_nuevo END,
        fecha_salida = CASE WHEN p_estado_nuevo = 'EN_CAMINO' THEN CURRENT_TIMESTAMP ELSE fecha_salida END,
        fecha_entrega = CASE WHEN p_estado_nuevo = 'ENTREGADO' THEN CURRENT_TIMESTAMP ELSE fecha_entrega END
    WHERE id_pedido = p_id_pedido;

    INSERT INTO historial_estado_pedido (id_pedido, estado_anterior, estado_nuevo, id_usuario, comentario)
    VALUES (p_id_pedido, v_pedido.estado, p_estado_nuevo, v_usuario.id_usuario, NULLIF(trim(p_comentario), ''));

    RETURN p_estado_nuevo;
END $$;

